def contrasts(df,name,label,title):
    rows=[]
    for family,g in df.groupby('family',sort=False):
        rows.append([f'\\multicolumn{{5}}{{l}}{{\\textit{{{esc(family)}}}}}'])
        for _,r in g.iterrows():
            adj='---' if pd.isna(r.sim_lo) else f'[{num(r.sim_lo)}, {num(r.sim_hi)}]'
            decision='Secondary'
            if not pd.isna(r.sim_lo):decision='Positive' if r.sim_lo>0 else ('Negative' if r.sim_hi<0 else 'Includes zero')
            rows.append([model(r.a)+' $-$ '+model(r.b),num(r['diff']),f'[{num(r.ci95_lo)}, {num(r.ci95_hi)}]',adj,decision])
    table(name,title,label,['Contrast ($a-b$)','Difference','95\\% interval','Adjusted interval','Decision'],rows,
          spec='L{.27\\linewidth}L{.10\\linewidth}L{.22\\linewidth}L{.22\\linewidth}L{.10\\linewidth}',long=True,
          note='Decisions refer only to declared adjusted families; secondary 95\\% intervals have no family-wide claim. User metrics are averaged over five seeds before resampling.')
