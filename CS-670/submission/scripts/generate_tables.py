def read(name):
    path = ROOT / 'data' / (name + '.csv')
    PROVENANCE.append({'source': str(path.relative_to(ROOT)),
                       'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    return pd.read_csv(path)

def esc(value):
    return str(value).replace('&', r'\&').replace('_', r'\_').replace('%', r'\%')

def model(value):
    if str(value) == 'dp_popularity': return 'DP popularity'
    value = str(value).replace('historical_B4', 'Hist. B4').replace('B4_main', 'B4')
    value = value.replace('B4_fixeddiag', 'B4 diag.').replace('fixed', 'FixedB')
    value = value.replace('full', 'Full').replace('two', 'Two').replace('pop', 'Pop')
    value = value.replace('_', ' ')
    value = re.sub(r'eps(\d+)', r'$\\epsilon=\1$', value)
    return esc(value)

def level(x):
    return {'nodp': 'No DP', 'clip': 'Clip only'}.get(str(x), str(x).replace('eps', ''))

def num(x, digits=6):
    return '---' if pd.isna(x) else f'{x:.{digits}f}'

def pm(m, sd, digits=5):
    if pd.isna(sd): return num(m, digits)
    return f'${m:.{digits}f}\\pm{sd:.{digits}f}$'

def sci(x):
    if pd.isna(x): return '---'
    if x == 0: return '$0$'
    a,b=f'{x:.3e}'.split('e')
    return f'${a}\\times10^{{{int(b)}}}$'

def table(name, caption, label, headers, rows, spec=None, note='', long=False):
    spec = spec or ('l' + 'r'*(len(headers)-1))
    if long:
        start = ('{\\small\n\\setlength{\\tabcolsep}{4pt}\n'
                 f'\\begin{{longtable}}{{{spec}}}\n\\caption{{{caption}}}\\label{{{label}}}\\\\\n'
                 '\\toprule\n' + ' & '.join(headers) + ' \\\\\n\\midrule\\endfirsthead\n'
                 f'\\multicolumn{{{len(headers)}}}{{l}}{{\\small\\itshape Table \\thetable\ (continued)}}\\\\\n'
                 '\\toprule\n' + ' & '.join(headers) + ' \\\\\n\\midrule\\endhead\n'
                 '\\midrule\n' + f'\\multicolumn{{{len(headers)}}}{{r}}{{\\footnotesize Continued on next page}}\\\\\n'
                 '\\endfoot\n\\bottomrule\\endlastfoot\n')
        end = '\\end{longtable}\n' + (f'\\tabnote{{{note}}}\n' if note else '') + '}\n'
    else:
        start = (f'\\begin{{table}}[tbp]\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n'
                 '\\setlength{\\tabcolsep}{4pt}\n' + f'\\begin{{tabular}}{{{spec}}}\\toprule\n'
                 + ' & '.join(headers) + ' \\\\\n\\midrule\n')
        end = '\\bottomrule\\end{tabular}\n' + (f'\\tabnote{{{note}}}\n' if note else '') + '\\end{table}\n'
    body = '\n'.join(' & '.join(map(str, r)) + r' \\' for r in rows) + '\n'
    (OUT/(name+'.tex')).write_text('% Generated by scripts/generate_tables.py; do not edit numeric cells.\n'+start+body+end)

